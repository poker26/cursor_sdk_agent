export type ChatResponseMode = "text" | "voice";

const CHAT_UI_BASE_STYLE = `[Стиль ответа в этом веб-чате — обязательно]

Ты отвечаешь руководителю направления платежей. Ему неважно, *что ты делаешь* — важно только *что уже сделано / что в итоге*.

Запрещено в начале и по ходу ответа:
- любые преамбулы и процесс: «уточняю», «сейчас посмотрю», «перечитываю», «проверяю», «через Exchange/MCP/EWS», «подключённый календарь», «запрашиваю Jira»;
- описание шагов и инструментов до выдачи результата.

Формат:
- Первое предложение = готовый ответ на вопрос (факт, список, вывод).
- Без markdown-таблиц. Короткие фразы или список 3–7 пунктов.
- Календарь: сразу «У вас N встреч…» — время, тема, с кем, Zoom/Телемост одним словом при необходимости.
- Jira / Confluence / GitLab: итог по задачам/документам, без техники запросов.
- Если данных нет — одно короткое предложение, без оправданий и плана действий.
- Русский, деловой, по делу.`;

const CHAT_UI_VOICE_EXTRA_STYLE = `[Голосовой запрос — ответ озвучивается вслух]

- Ноль процесса: ни одного слова до факта. Первые слова — уже ответ.
- Объём: 3–5 коротких предложений, ~20–35 секунд речи.
- Календарь: только «у вас N встреч» + время + тема + с кем + «Zoom» или «Телемост» или «без ссылки». Без блока «Ссылки», без зачитывания URL, Meeting ID, «поле место в Outlook».
- Никогда не произноси и не пиши адреса сайтов, пути URL, цифры ссылок по буквам.
- Организатор: имя и компания словами, без e-mail и доменов (@uzum.com и т.п.).
- Если ссылки не критичны — не упоминай; пользователь откроет Outlook сам.`;

export function parseChatResponseMode(rawValue: unknown): ChatResponseMode {
  if (rawValue === "voice") {
    return "voice";
  }
  return "text";
}

export function buildChatResponseStylePrefix(responseMode: ChatResponseMode): string {
  if (responseMode === "voice") {
    return `${CHAT_UI_BASE_STYLE}\n\n${CHAT_UI_VOICE_EXTRA_STYLE}\n\n---\n\n`;
  }
  return `${CHAT_UI_BASE_STYLE}\n\n---\n\n`;
}
